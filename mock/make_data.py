"""Write mock/data.js from the test customers of a case folder.

    python mock/make_data.py <case_folder>
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent


def main(argv):
    source = pathlib.Path(argv[1]) / "test-environment" / "test-customers.json"
    data = json.loads(source.read_text(encoding="utf-8"))
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    (HERE / "data.js").write_text("// Generated by make_data.py from " + source.name + ". Do not edit.\nexport default " + body + ";\n",
                                  encoding="utf-8", newline="\n")
    print(f"mock/data.js written: {len(data['customers'])} customers, {len(body)} bytes")


if __name__ == "__main__":
    main(sys.argv)
